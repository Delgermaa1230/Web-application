export function migrateSqlite(db) {
  db.exec('PRAGMA foreign_keys = ON');
  db.exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  const applied = db.prepare('SELECT version FROM schema_migrations').all().map(row => row.version);
  if (!applied.includes(1)) {
    db.exec('BEGIN IMMEDIATE');
    try {
      db.exec(sqliteInitial);
      // Older local databases have tutor_slots without is_active.
      if (!db.prepare('PRAGMA table_info(tutor_slots)').all().some(column => column.name === 'is_active')) {
        db.exec('ALTER TABLE tutor_slots ADD COLUMN is_active INTEGER NOT NULL DEFAULT 1');
      }
      db.prepare('INSERT INTO schema_migrations (version) VALUES (?)').run(1);
      db.exec('COMMIT');
    } catch (error) {
      db.exec('ROLLBACK');
      throw error;
    }
  }
  if (!applied.includes(2)) {
    db.exec('BEGIN IMMEDIATE');
    try {
      db.exec(sqliteLessons);
      const tutors = db.prepare('SELECT teacher_id, lessons, lesson_info, price, mode FROM tutors').all();
      const insert = db.prepare(`INSERT OR IGNORE INTO tutor_lessons
        (tutor_id, lesson_name, description, price, mode) VALUES (?, ?, ?, ?, ?)`);
      for (const tutor of tutors) {
        for (const lesson of JSON.parse(tutor.lessons)) {
          const name = String(lesson.lesson_name || '').trim();
          if (name) insert.run(tutor.teacher_id, name, tutor.lesson_info, tutor.price, tutor.mode);
        }
      }
      db.prepare('INSERT INTO schema_migrations (version) VALUES (?)').run(2);
      db.exec('COMMIT');
    } catch (error) {
      db.exec('ROLLBACK');
      throw error;
    }
  }
  if (!applied.includes(3)) {
    db.exec('BEGIN IMMEDIATE');
    try {
      if (!db.prepare('PRAGMA table_info(bookings)').all().some(column => column.name === 'lesson_id')) {
        db.exec('ALTER TABLE bookings ADD COLUMN lesson_id INTEGER REFERENCES tutor_lessons(id)');
      }
      db.exec(`UPDATE bookings SET lesson_id = (
        SELECT l.id FROM tutor_slots s JOIN tutor_lessons l
          ON l.tutor_id = s.tutor_id AND l.lesson_name = bookings.lesson_name
        WHERE s.id = bookings.slot_id LIMIT 1
      )`);
      db.prepare('INSERT INTO schema_migrations (version) VALUES (?)').run(3);
      db.exec('COMMIT');
    } catch (error) {
      db.exec('ROLLBACK');
      throw error;
    }
  }
  if (!applied.includes(4)) {
    db.exec('BEGIN IMMEDIATE');
    try {
      db.exec(`CREATE TABLE reviews (
        id INTEGER PRIMARY KEY,
        booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE CASCADE,
        tutor_id INTEGER NOT NULL REFERENCES tutors(teacher_id) ON DELETE CASCADE,
        lesson_id INTEGER NOT NULL REFERENCES tutor_lessons(id) ON DELETE CASCADE,
        student_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5),
        comment TEXT NOT NULL,
        is_visible INTEGER NOT NULL DEFAULT 1,
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
      CREATE INDEX reviews_tutor_visible ON reviews(tutor_id, is_visible);
      CREATE INDEX reviews_lesson_visible ON reviews(lesson_id, is_visible);`);
      db.prepare('INSERT INTO schema_migrations (version) VALUES (?)').run(4);
      db.exec('COMMIT');
    } catch (error) {
      db.exec('ROLLBACK');
      throw error;
    }
  }
  if (!applied.includes(5)) {
    db.exec('BEGIN IMMEDIATE');
    try {
      db.exec('ALTER TABLE bookings ADD COLUMN price_amount INTEGER');
      db.exec('ALTER TABLE bookings ADD COLUMN duration_minutes INTEGER');
      db.exec('ALTER TABLE bookings ADD COLUMN mode TEXT');
      db.exec(`UPDATE bookings SET
        price_amount = (SELECT l.price FROM tutor_lessons l WHERE l.id = bookings.lesson_id),
        duration_minutes = (SELECT l.duration_minutes FROM tutor_lessons l WHERE l.id = bookings.lesson_id),
        mode = (SELECT l.mode FROM tutor_lessons l WHERE l.id = bookings.lesson_id)`);
      db.prepare('INSERT INTO schema_migrations (version) VALUES (?)').run(5);
      db.exec('COMMIT');
    } catch (error) {
      db.exec('ROLLBACK');
      throw error;
    }
  }
  if (!applied.includes(6)) {
    db.exec('BEGIN IMMEDIATE');
    try {
      db.exec(`UPDATE tutor_lessons SET price = (
        SELECT ROUND(t.price * tutor_lessons.duration_minutes / 60.0)
        FROM tutors t WHERE t.teacher_id = tutor_lessons.tutor_id
      )`);
      db.prepare('INSERT INTO schema_migrations (version) VALUES (?)').run(6);
      db.exec('COMMIT');
    } catch (error) {
      db.exec('ROLLBACK');
      throw error;
    }
  }
}

export async function migratePostgres(sql) {
  await sql.query(`CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`);
  const applied = (await sql.query('SELECT version FROM schema_migrations')).map(row => row.version);
  if (!applied.includes(1)) {
    await sql.transaction([
      ...postgresInitial.map(statement => sql.query(statement)),
      sql.query('INSERT INTO schema_migrations (version) VALUES ($1) ON CONFLICT DO NOTHING', [1]),
    ]);
  }
  if (!applied.includes(2)) {
    await sql.transaction([
      ...postgresLessons.map(statement => sql.query(statement)),
      sql.query('INSERT INTO schema_migrations (version) VALUES ($1) ON CONFLICT DO NOTHING', [2]),
    ]);
  }
  if (!applied.includes(3)) {
    await sql.transaction([
      sql.query('ALTER TABLE bookings ADD COLUMN IF NOT EXISTS lesson_id BIGINT REFERENCES tutor_lessons(id)'),
      sql.query(`UPDATE bookings b SET lesson_id = (
        SELECT l.id FROM tutor_slots s JOIN tutor_lessons l
          ON l.tutor_id = s.tutor_id AND l.lesson_name = b.lesson_name
        WHERE s.id = b.slot_id LIMIT 1
      ) WHERE b.lesson_id IS NULL`),
      sql.query('INSERT INTO schema_migrations (version) VALUES ($1) ON CONFLICT DO NOTHING', [3]),
    ]);
  }
  if (!applied.includes(4)) {
    await sql.transaction([
      sql.query(`CREATE TABLE reviews (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE CASCADE,
        tutor_id BIGINT NOT NULL REFERENCES tutors(teacher_id) ON DELETE CASCADE,
        lesson_id BIGINT NOT NULL REFERENCES tutor_lessons(id) ON DELETE CASCADE,
        student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5),
        comment TEXT NOT NULL,
        is_visible BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )`),
      sql.query('CREATE INDEX reviews_tutor_visible ON reviews(tutor_id, is_visible)'),
      sql.query('CREATE INDEX reviews_lesson_visible ON reviews(lesson_id, is_visible)'),
      sql.query('INSERT INTO schema_migrations (version) VALUES ($1) ON CONFLICT DO NOTHING', [4]),
    ]);
  }
  if (!applied.includes(5)) {
    await sql.transaction([
      sql.query('ALTER TABLE bookings ADD COLUMN IF NOT EXISTS price_amount INTEGER'),
      sql.query('ALTER TABLE bookings ADD COLUMN IF NOT EXISTS duration_minutes INTEGER'),
      sql.query('ALTER TABLE bookings ADD COLUMN IF NOT EXISTS mode TEXT'),
      sql.query(`UPDATE bookings b SET price_amount = l.price,
        duration_minutes = l.duration_minutes, mode = l.mode
        FROM tutor_lessons l WHERE l.id = b.lesson_id AND b.price_amount IS NULL`),
      sql.query('INSERT INTO schema_migrations (version) VALUES ($1) ON CONFLICT DO NOTHING', [5]),
    ]);
  }
  if (!applied.includes(6)) {
    await sql.transaction([
      sql.query(`UPDATE tutor_lessons l SET price = ROUND(t.price * l.duration_minutes / 60.0)::integer
        FROM tutors t WHERE t.teacher_id = l.tutor_id`),
      sql.query('INSERT INTO schema_migrations (version) VALUES ($1) ON CONFLICT DO NOTHING', [6]),
    ]);
  }
}

export async function assertPostgresMigrated(sql) {
  const table = await sql.query("SELECT to_regclass('schema_migrations') AS name");
  if (!table[0]?.name) {
    throw new Error('Neon schema is not migrated. Run npm run db:migrate -- --postgres on staging first.');
  }
  const rows = await sql.query('SELECT MAX(version)::integer AS version FROM schema_migrations');
  if (Number(rows[0]?.version || 0) < latestMigrationVersion) {
    throw new Error(`Neon schema is at version ${rows[0]?.version || 0}; version ${latestMigrationVersion} is required. Run the migration command on staging first.`);
  }
}
